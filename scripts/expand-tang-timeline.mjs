for (const [file, newEntries] of Object.entries(additions)) {
  const p = 'data/tang/emperors/' + file;
  const d = JSON.parse(fs.readFileSync(p, 'utf8'));
  // 合并：按date排序，去重
  const existing = d.timeline || [];
  const seen = new Set(existing.map(t => t.date));
  for (const e of newEntries) {
    if (!seen.has(e.date)) existing.push(e);
  }
  existing.sort((a,b) => parseInt(a.date) - parseInt(b.date));
  d.timeline = existing;
  fs.writeFileSync(p, JSON.stringify(d, null, 2));
  console.log('OK', file, d.name, '共', existing.length, '条');
}
